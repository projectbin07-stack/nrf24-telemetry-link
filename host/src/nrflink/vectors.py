class _Recorder:
    """Drives two endpoints and records every call and observable effect."""

    def __init__(self, config: LinkConfig) -> None:
        self.steps: list[dict[str, Any]] = []
        self._events: dict[str, dict[str, list[dict[str, Any]]]] = {
            "a": {"delivered": [], "results": []},
            "b": {"delivered": [], "results": []},
        }
        self.ep = {name: self._make(name, config) for name in ("a", "b")}

    def _make(self, name: str, config: LinkConfig) -> LinkEndpoint:
        def deliver(channel: Channel, data: bytes) -> None:
            self._events[name]["delivered"].append({"channel": int(channel), "data": data.hex()})

        def result(seq: int, ok: bool) -> None:
            self._events[name]["results"].append({"seq": seq, "ok": ok})

        return LinkEndpoint(LinkConfig(**asdict(config)), deliver=deliver, result=result)

    def _flush(self, name: str, step: dict[str, Any]) -> None:
        ev = self._events[name]
        step["delivered"] = ev["delivered"]
        step["results"] = ev["results"]
        self._events[name] = {"delivered": [], "results": []}
        self.steps.append(step)

    def send_reliable(self, ep: str, data: bytes, now: int) -> bool:
        ok = self.ep[ep].send_reliable(data, now)
        self._flush(
            ep, {"ep": ep, "op": "send_reliable", "now": now, "data": data.hex(), "ret": ok}
        )
        return ok

    def send_unreliable(self, ep: str, data: bytes) -> bool:
        ok = self.ep[ep].send_unreliable(data)
        self._flush(ep, {"ep": ep, "op": "send_unreliable", "data": data.hex(), "ret": ok})
        return ok

    def next_frame(
        self, ep: str, now: int, hop: int = 0, phase: int = 0, idle: bool = False
    ) -> bytes:
        f = self.ep[ep].next_frame(now, hop, phase, idle)
        self._flush(
            ep,
            {"ep": ep, "op": "next_frame", "now": now, "hop": hop, "phase": phase,
             "idle": idle, "frame": f.hex()},
        )  # fmt: skip
        return f

    def tx_result(self, ep: str, acked: bool) -> None:
        self.ep[ep].on_tx_result(acked)
        self._flush(ep, {"ep": ep, "op": "tx_result", "acked": acked})

    def on_frame(self, ep: str, frame: bytes, now: int) -> bool:
        ok = self.ep[ep].on_frame(frame, now) is not None
        self._flush(ep, {"ep": ep, "op": "on_frame", "now": now, "frame": frame.hex(), "ret": ok})
        return ok

    def poll(self, ep: str, now: int) -> None:
        self.ep[ep].poll(now)
        self._flush(ep, {"ep": ep, "op": "poll", "now": now})

    def stats(self) -> None:
        for name in ("a", "b"):
            self._flush(name, {"ep": name, "op": "stats", "stats": asdict(self.ep[name].stats)})

    def transfer(
        self, src: str, dst: str, now: int, *, drop: bool = False, idle: bool = False
    ) -> bytes:
        f = self.next_frame(src, now, hop=now % 8, phase=now % 16, idle=idle)
        if f:
            self.tx_result(src, not drop)
            if not drop:
                self.on_frame(dst, f, now)
        return f


def _pattern(n: int, start: int = 0) -> bytes:
    return bytes((start + 7 * i) & 0xFF for i in range(n))


def _scenarios() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []

    cfg = LinkConfig(reliable_timeout_ms=50, reliable_max_attempts=4)
    r = _Recorder(cfg)
    r.send_reliable("a", _pattern(70, 3), 0)
    r.transfer("a", "b", 1)
    r.transfer("a", "b", 2, drop=True)
    r.transfer("a", "b", 3)
    r.transfer("a", "b", 4)
    r.transfer("b", "a", 5, drop=True)  # the ack is lost
    r.poll("a", 40)
    r.poll("a", 54)  # timeout: whole message again
    for t in (55, 56, 57):
        r.transfer("a", "b", t)
    r.transfer("b", "a", 58)
    r.send_reliable("a", _pattern(5, 9), 60)
    r.transfer("a", "b", 61)
    r.transfer("b", "a", 62)
    r.stats()
    out.append({"name": "reliable fragments, lost fragment, lost ack, retransmission",
                "config": asdict(cfg), "steps": r.steps})  # fmt: skip

    cfg = LinkConfig()
    r = _Recorder(cfg)
    r.send_unreliable("a", _pattern(8, 1))
    r.send_unreliable("a", _pattern(8, 2))  # replaces
    r.transfer("a", "b", 0)
    r.send_unreliable("a", _pattern(60, 4))  # 3 fragments
    r.transfer("a", "b", 1)
    r.send_unreliable("a", _pattern(4, 5))  # refused: part way through
    r.transfer("a", "b", 2, drop=True)  # aborts the rest
    r.send_unreliable("a", _pattern(30, 6))
    f0 = r.transfer("a", "b", 3)
    r.on_frame("b", f0, 3)  # duplicate fragment
    r.transfer("a", "b", 4)
    r.on_frame("b", f0, 4)  # fragment of a delivered message
    r.send_reliable("b", _pattern(3, 7), 5)
    r.send_unreliable("a", _pattern(2, 8))
    r.transfer("b", "a", 6)
    r.transfer("a", "b", 7)  # carries the ack
    r.stats()
    out.append({"name": "best effort replace, abort, duplicates, piggybacked ack",
                "config": asdict(cfg), "steps": r.steps})  # fmt: skip

    cfg = LinkConfig(initial_reliable_seq=254, initial_unreliable_seq=255)
    r = _Recorder(cfg)
    r.send_unreliable("a", _pattern(20, 1))
    f = r.next_frame("a", 0)
    r.tx_result("a", True)
    bad = bytearray(f)
    bad[6] ^= 0x10
    r.on_frame("b", bytes(bad), 0)  # CRC error
    r.on_frame("b", bytes.fromhex("6000000000aa"), 0)  # unknown type
    r.on_frame("b", bytes.fromhex("2000010000aa"), 0)  # fragment index 0 of 2, too short
    r.on_frame("b", bytes.fromhex("00000000"), 0)  # shorter than a header
    for i in range(4):  # sequence numbers wrap
        r.send_reliable("a", _pattern(3, i), 10 * i)
        r.transfer("a", "b", 10 * i + 1)
        r.transfer("b", "a", 10 * i + 2)
    r.stats()
    out.append({"name": "crc error, malformed frames, sequence wrap",
                "config": asdict(cfg), "steps": r.steps})  # fmt: skip

    cfg = LinkConfig(reliable_timeout_ms=15, reliable_max_attempts=6)
    r = _Recorder(cfg)
    rng = random.Random(2024)
    for now in range(0, 400, 2):
        if rng.random() < 0.2:
            r.send_reliable("a", _pattern(rng.randint(1, 120), now), now)
        if rng.random() < 0.15:
            r.send_reliable("b", _pattern(rng.randint(1, 60), now + 1), now)
        if rng.random() < 0.4:
            r.send_unreliable("a", _pattern(rng.randint(1, 160), now + 2))
        r.transfer("a", "b", now, drop=rng.random() < 0.25, idle=rng.random() < 0.3)
        r.transfer("b", "a", now + 1, drop=rng.random() < 0.25, idle=rng.random() < 0.3)
    r.stats()
    out.append({"name": "random lossy exchange (seed 2024)", "config": asdict(cfg),
                "steps": r.steps})  # fmt: skip
    return out


def build_vectors() -> dict[str, Any]:
    serial = [
        (SerialKind.MESSAGE, 0, bytes((1, 1, 1)) + encode_message(Command(1, 100))),
        (SerialKind.COMMAND_RESULT, 255, bytes((7, 1))),
        (SerialKind.LOG, 3, b"gateway ready"),
        (SerialKind.REQUEST_STATS, 9, b""),
        (SerialKind.SEND_COMMAND, 10, bytes(range(1, 200))),  # longest body the C++ side accepts
    ]
    stats = GatewayStats(123456, 1000, 2, 1, 5, 10, 900, 7, 11, 10, 1, 4, 2, 3, 1, 42, 88)
    hop_params = [
        (0x4E524634, 2, 80, 2, 8),
        (1, 0, 125, 1, 32),
        (0, 10, 20, 5, 3),
        (0xDEADBEEF, 2, 125, 3, 16),
    ]
    headers = [
        FrameHeader(FrameType.IDLE, False, 0, 0, 0, 1, 0, 0),
        FrameHeader(FrameType.RELIABLE, True, 15, 255, 15, 16, 128, 31),
        FrameHeader(FrameType.UNRELIABLE, False, 7, 42, 1, 3, 0, 5),
    ]
    return {
        "comment": (
            "Generated by `nrflink vectors --write` (host/src/nrflink/vectors.py). "
            "Read by test/test_vectors (C++) and host/tests (Python)."
        ),
        "crc16": [
            {"ascii": "123456789", "crc": f"{crc16_ccitt(b'123456789'):04x}"},
            {"ascii": "", "crc": f"{crc16_ccitt(b''):04x}"},
        ],
        "cobs": [
            {"raw": raw.hex(), "encoded": cobs_encode(raw).hex()}
            for raw in (
                b"",
                b"\x00",
                b"\x00\x00",
                b"\x11\x22\x00\x33",
                b"\x11\x22\x33\x44",
                b"\x11\x00\x00\x00",
                bytes(range(1, 255)),
                bytes(range(0, 255)),
                bytes(range(1, 256)),
            )
        ],
        "messages": [
            {
                "name": name,
                "type": message_name(m),
                "fields": message_to_dict(m),
                "hex": encode_message(m).hex(),
            }
            for name, m in _messages()
        ],
        "invalid_messages": _invalid_messages(),
        "serial_frames": [
            {"kind": int(k), "seq": s, "body": b.hex(), "wire": encode_wire(k, s, b).hex()}
            for k, s, b in serial
        ],
        "gateway_stats": {"fields": asdict(stats), "hex": encode_gateway_stats(stats).hex()},
        "hop_sequences": [
            {
                "seed": seed,
                "first": first,
                "last": last,
                "spacing": spacing,
                "count": count,
                "channels": HopSequence.generated(seed, first, last, spacing, count).channels,
            }
            for seed, first, last, spacing, count in hop_params
        ],
        "link_frames": [
            {"header": {**asdict(h), "type": int(h.type)}, "hex": encode_header(h).hex()}
            for h in headers
        ],
        "link_scenarios": _scenarios(),
    }


def render(vectors: dict[str, Any]) -> str:
    return json.dumps(vectors, indent=1) + "\n"


def find_repo_file(relative: Path, start: Path | None = None) -> Path | None:
    here = (start or Path.cwd()).resolve()
    for d in (here, *here.parents):
        candidate = d / relative
        if candidate.is_file():
            return candidate
    return None
