"""Shared test vectors: ``test/vectors/link_vectors.json``.

The file is generated by :func:`build_vectors` and read by both test suites:
the pytest suite (``host/tests/test_vectors.py``) and the C++ Unity test
``test/test_vectors``. Sections:

* ``crc16`` / ``cobs``: independent reference values (the published
  CRC-16/CCITT-FALSE check value, the worked COBS examples).
* ``messages`` / ``invalid_messages``: application schema encodings.
* ``serial_frames`` / ``gateway_stats``: gateway USB framing.
* ``hop_sequences``: channel lists for given seeds.
* ``link_frames``: header encodings.
* ``link_scenarios``: scripted calls on two link endpoints with every
  returned frame, delivery, result callback and final statistics recorded.
  The C++ test replays the calls and must produce identical bytes, which is
  what ties the simulator's Python port to the firmware's C++ link layer.

Floats are exactly representable in binary32 so both sides compare with ==.
"""

